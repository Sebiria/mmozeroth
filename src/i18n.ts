// Argent en pièces d'or, d'argent et de cuivre (100 cuivre = 1 argent, 100 argent = 1 or).
function gold(copper: number, g: string, s: string, c: string) {
  const parts: string[] = [];
  if (copper >= 10000) parts.push(`${Math.floor(copper / 10000)} ${g}`);
  if (copper >= 100) parts.push(`${Math.floor(copper / 100) % 100} ${s}`);
  parts.push(`${copper % 100} ${c}`);
  return parts.join(" ");
}

